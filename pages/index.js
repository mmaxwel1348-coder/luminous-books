function paginateBookText(rawText, charsPerPage = 720) {
  if (!rawText || !rawText.trim()) return [];
  const paragraphs = rawText
    .split(/\n\s*\n/)
    .map(p => p.trim())
    .filter(Boolean);

  const pages = [];
  let currentBlocks = [];
  let currentLen = 0;

  for (const para of paragraphs) {
    const isHeading =
      /^(CHAPTER\s+[A-Z0-9]+|FOREWORD|INTRODUCTION|DEDICATION|ACKNOWLEDGMENTS|CONCLUSION TO THE BOOK|CLOSING PRAYER|BIBLIOGRAPHY)/i.test(
        para.split('\n')[0]
      );

    if (isHeading && currentBlocks.length > 0 && currentLen > 140) {
      pages.push(currentBlocks);
      currentBlocks = [para];
      currentLen = para.length;
      continue;
    }

    if (currentLen + para.length > charsPerPage && currentBlocks.length > 0) {
      pages.push(currentBlocks);
      currentBlocks = [para];
      currentLen = para.length;
    } else {
      currentBlocks.push(para);
      currentLen += para.length + 2;
    }
  }

  if (currentBlocks.length > 0) {
    pages.push(currentBlocks);
  }

  return pages;
}

